// The guard runs when the price changes, not every minute: each run puts the
// next one on the operating system's scheduler at the exact boundary, so the
// machine is idle in between. Nothing here polls.
//
//   Linux    a systemd --user timer whose OnCalendar is that one instant
//            (Persistent, so a run missed while the machine was off happens at
//            the next boot)
//   Windows  a one-time scheduled task started through a .vbs shim, which is
//            what keeps a console window from flashing on screen

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { logLine, stateDir } from "./config.mjs";
import { loadConfig } from "./config.mjs";
import { nextChange } from "./peak.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));

export const UNIT = "deepseek-peak-guard";
export const TASK = "DeepSeekPeakGuard";
export const VBS = "run-hidden.vbs";

export function cliPath() {
  return path.join(HERE, "..", "bin", "deepseek-peak-guard.mjs");
}

/** interpreter is magpie's own bun when a plugin host armed this, node otherwise. */
export function interpreter() {
  return process.execPath;
}

function powershell(script) {
  return execFileSync(
    "powershell.exe",
    ["-NoProfile", "-NonInteractive", "-WindowStyle", "Hidden", "-Command", script],
    { encoding: "utf8", windowsHide: true, stdio: ["ignore", "pipe", "pipe"] },
  ).trim();
}

function sane(text) {
  return String(text ?? "").replace(/\r?\n/g, " ").trim();
}

// ---- the boundary -----------------------------------------------------------

/** nextBoundary is when the rule changes next, from the clock and the config. */
export function nextBoundary(now = new Date(), config = loadConfig()) {
  const next = nextChange(now, config);
  if (!next) throw new Error("no peak boundary within 8 days; check windows/weekdays in config.json");
  return next;
}

// ---- Windows ----------------------------------------------------------------

export function vbsPath() {
  return path.join(path.dirname(cliPath()), VBS);
}

export function vbsContent() {
  const interp = interpreter();
  const cli = cliPath();
  return [
    "' Generated by deepseek-peak-guard: run the guard with no console window.",
    "Dim shell, args, i",
    'Set shell = CreateObject("WScript.Shell")',
    'args = ""',
    "For i = 0 To WScript.Arguments.Count - 1",
    '  args = args & " " & Chr(34) & WScript.Arguments(i) & Chr(34)',
    "Next",
    `shell.Run """${interp}"" ""${cli}""" & args, 0, False`,
    "",
  ].join("\r\n");
}

function writeVbs() {
  const file = vbsPath();
  const content = vbsContent();
  try {
    if (fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") === content.replace(/\r\n/g, "\n")) return file;
  } catch {
    // no file yet
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return file;
}

function armWindows(at) {
  const vbs = writeVbs();
  const when = `${at.getFullYear()}-${pad(at.getMonth() + 1)}-${pad(at.getDate())}T${pad(at.getHours())}:${pad(at.getMinutes())}:00`;
  const script = [
    `$action = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument '"${vbs}" tick'`,
    `$trigger = New-ScheduledTaskTrigger -Once -At ([datetime]'${when}')`,
    "$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Hours 1) -Hidden",
    `Register-ScheduledTask -TaskName '${TASK}' -Action $action -Trigger $trigger -Settings $settings -Description 'DeepSeek peak guard: switch the DeepSeek Official provider at the price boundary' -Force | Out-Null`,
    `(Get-ScheduledTask -TaskName '${TASK}').Triggers[0].StartBoundary`,
  ].join("; ");
  try {
    const boundary = powershell(script);
    return { at: at.toISOString(), boundary, task: TASK, scheduler: "schtasks", vbs };
  } catch (error) {
    return { at: at.toISOString(), error: sane(error?.stderr ?? error?.message ?? error), task: TASK };
  }
}

function pad(number) {
  return String(number).padStart(2, "0");
}

// ---- Linux ------------------------------------------------------------------

function unitDir() {
  const base = process.env.XDG_CONFIG_HOME?.trim() || path.join(os.homedir(), ".config");
  return path.join(base, "systemd", "user");
}

function serviceContent() {
  const places = [path.dirname(interpreter()), path.join(os.homedir(), ".local", "bin"), "/usr/local/bin", "/usr/bin", "/bin"];
  return [
    "[Unit]",
    "Description=DeepSeek peak guard for magpie (deepseek-peak-guard)",
    "",
    "[Service]",
    "Type=oneshot",
    `Environment="PATH=${[...new Set(places)].join(":")}"`,
    `ExecStart=${interpreter()} ${cliPath()} tick`,
    "",
  ].join("\n");
}

function timerContent(at) {
  const when = `${at.getFullYear()}-${pad(at.getMonth() + 1)}-${pad(at.getDate())} ${pad(at.getHours())}:${pad(at.getMinutes())}:00`;
  return [
    "[Unit]",
    "Description=DeepSeek peak guard: the next price boundary",
    "",
    "[Timer]",
    `OnCalendar=${when}`,
    "AccuracySec=1s",
    "Persistent=true",
    "",
    "[Install]",
    "WantedBy=timers.target",
    "",
  ].join("\n");
}

function writeIfChanged(file, content) {
  try {
    if (fs.readFileSync(file, "utf8") === content) return false;
  } catch {
    // no file yet
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

function armLinux(at) {
  const dir = unitDir();
  const service = path.join(dir, `${UNIT}.service`);
  const timer = path.join(dir, `${UNIT}.timer`);
  const when = `${at.getFullYear()}-${pad(at.getMonth() + 1)}-${pad(at.getDate())} ${pad(at.getHours())}:${pad(at.getMinutes())}:00`;
  writeIfChanged(service, serviceContent());
  writeIfChanged(timer, timerContent(at));
  try {
    execFileSync("systemctl", ["--user", "daemon-reload"], { windowsHide: true, stdio: "ignore" });
    execFileSync("systemctl", ["--user", "enable", "--now", `${UNIT}.timer`], { windowsHide: true, stdio: "ignore" });
    return { at: at.toISOString(), boundary: when, timer, scheduler: "systemd" };
  } catch (error) {
    return { at: at.toISOString(), error: sane(error?.stderr ?? error?.message ?? error), timer };
  }
}

// ---- the two faces the plugin uses -----------------------------------------

/** arm puts the next boundary on the OS scheduler, replacing the previous one. */
export function arm({ now = new Date(), config = loadConfig() } = {}) {
  const next = nextBoundary(now, config);
  const at = next.at;
  const result = process.platform === "win32" ? armWindows(at) : armLinux(at);
  return { ...result, peak: next.peak, inMinutes: next.minutes };
}

/** disarm takes the guard off the OS scheduler. */
export function disarm() {
  if (process.platform === "win32") {
    try {
      powershell(`Unregister-ScheduledTask -TaskName '${TASK}' -Confirm:$false -ErrorAction SilentlyContinue`);
      return { removed: true, task: TASK };
    } catch (error) {
      return { removed: false, reason: sane(error?.message ?? error) };
    }
  }
  try {
    execFileSync("systemctl", ["--user", "disable", "--now", `${UNIT}.timer`], { windowsHide: true, stdio: "ignore" });
  } catch {
    // already gone
  }
  for (const file of [`${UNIT}.timer`, `${UNIT}.service`]) {
    fs.rmSync(path.join(unitDir(), file), { force: true });
  }
  try {
    execFileSync("systemctl", ["--user", "daemon-reload"], { windowsHide: true, stdio: "ignore" });
  } catch {
    // nothing to reload
  }
  return { removed: true };
}

/** scheduleState says what the OS scheduler is holding right now. */
export function scheduleState() {
  if (process.platform === "win32") {
    try {
      const out = powershell(
        `$t = Get-ScheduledTask -TaskName '${TASK}' -ErrorAction SilentlyContinue; if ($t) { $t.Triggers[0].StartBoundary } else { '' }`,
      );
      return { scheduler: "schtasks", task: TASK, present: Boolean(out), next: out || null };
    } catch (error) {
      return { scheduler: "schtasks", task: TASK, present: false, error: sane(error?.message ?? error) };
    }
  }
  const timer = path.join(unitDir(), `${UNIT}.timer`);
  let next = null;
  try {
    const out = execFileSync("systemctl", ["--user", "list-timers", `${UNIT}.timer`, "--no-pager"], {
      encoding: "utf8",
      windowsHide: true,
      stdio: ["ignore", "pipe", "ignore"],
    });
    next = out.split("\n")[1]?.trim() || null;
  } catch {
    // no timer
  }
  return { scheduler: "systemd", timer, present: fs.existsSync(timer), next };
}

/** armQuietly is what the plugin calls on load: a failure is logged, not thrown. */
export function armQuietly(options = {}) {
  try {
    const result = arm(options);
    logLine(
      result.error
        ? `the next boundary could not be put on the scheduler: ${result.error}`
        : `the next boundary is ${result.boundary ?? result.at} on ${result.scheduler}`,
    );
    return result;
  } catch (error) {
    logLine(`the next boundary could not be put on the scheduler: ${String(error?.message ?? error)}`);
    return { error: String(error?.message ?? error) };
  }
}

export function stateFile() {
  fs.mkdirSync(stateDir(), { recursive: true });
  return path.join(stateDir(), "schedule.json");
}
