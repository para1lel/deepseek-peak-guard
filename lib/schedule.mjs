// The guard's clock lives on the operating system's scheduler, installed once:
//
//   Linux    one systemd --user timer, OnCalendar=Mon..Fri 09:00:00 (and the
//            other boundaries), Persistent=true so a run missed while the
//            machine was off happens at the next boot
//   Windows  one scheduled task with a weekly trigger per boundary, started
//            through a .vbs shim so no console window appears
//
// Neither of them is ever rewritten from inside a run: a timer or task that
// re-arms itself is how a schedule turns into a fork storm. `install-schedule`
// writes the schedule, the scheduler runs it, and that is the whole loop.
//
// The scheduler runs the same small shim in the guard's state directory, and
// the shim reads the interpreter and script path from cli.txt. `magpie plugin
// update` replaces the plugin folder, so a task pointing straight into it
// breaks with "run-hidden.vbs not found"; rewriting one text file is enough to
// repair that, and loading the plugin does exactly that.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ensureDir, loadConfig, stateDir } from "./config.mjs";
import { describeSchedule, systemdCalendar, taskPlan } from "./calendar.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));

export const UNIT = "deepseek-peak-guard";
export const TASK = "DeepSeekPeakGuard";
export const CLI_FILE = "cli.txt";
export const WINDOWS_SHIM = "run-hidden.vbs";
export const POSIX_SHIM = "tick.sh";

/** cliPath is this plugin's command line, wherever magpie installed it. */
export function cliPath() {
  return path.join(HERE, "..", "bin", "deepseek-peak-guard.mjs");
}

/** interpreter is a node that will still be there next week, when there is one. */
export function interpreter() {
  const candidates =
    process.platform === "win32"
      ? [path.join(process.env.ProgramFiles?.trim() || "C:\\Program Files", "nodejs", "node.exe"), process.execPath]
      : ["/usr/bin/node", "/usr/local/bin/node", process.execPath];
  for (const candidate of candidates) {
    try {
      if (candidate && fs.statSync(candidate).isFile()) return candidate;
    } catch {
      // the next candidate
    }
  }
  return process.execPath;
}

function sane(text) {
  return String(text ?? "").replace(/\r?\n/g, " ").trim();
}

function pad(number) {
  return String(number).padStart(2, "0");
}

// ---- files ------------------------------------------------------------------

function writeIfChanged(file, content) {
  try {
    if (fs.readFileSync(file, "utf8") === content) return false;
  } catch {
    // no file yet
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, content);
  fs.renameSync(tmp, file);
  return true;
}

/**
 * windowsShim runs the CLI with window style 0. The interpreter is started
 * hidden, and anything it starts (magpie) inherits that hidden console, so a
 * tick that shells out to magpie still shows nothing.
 */
export function windowsShim() {
  return [
    "' Generated by deepseek-peak-guard; rewritten by install-schedule.",
    "Option Explicit",
    "Dim fso, shell, home, stream, interp, cli, cmd, i, arg",
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    'Set shell = CreateObject("WScript.Shell")',
    "home = fso.GetParentFolderName(WScript.ScriptFullName)",
    'Set stream = fso.OpenTextFile(home & "\\cli.txt", 1)',
    "interp = stream.ReadLine",
    "cli = stream.ReadLine",
    "stream.Close",
    'cmd = """" & interp & """ """ & cli & """"',
    "For i = 0 To WScript.Arguments.Count - 1",
    "  arg = WScript.Arguments(i)",
    '  cmd = cmd & " """ & arg & """"',
    "Next",
    "shell.Run cmd, 0, False",
    "",
  ].join("\r\n");
}

/** posixShim is the same indirection for systemd: /bin/sh, then cli.txt. */
export function posixShim() {
  return [
    "#!/bin/sh",
    "# Generated by deepseek-peak-guard; rewritten by install-schedule.",
    'here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)',
    "interp=$(sed -n '1p' \"$here/cli.txt\")",
    "cli=$(sed -n '2p' \"$here/cli.txt\")",
    'exec "$interp" "$cli" "$@"',
    "",
  ].join("\n");
}

function exists(file) {
  try {
    return Boolean(file) && fs.statSync(file).isFile();
  } catch {
    return false;
  }
}

function readLauncher(file) {
  try {
    const [interp, cli] = fs.readFileSync(file, "utf8").split(/\r?\n/);
    return { interp: (interp ?? "").trim(), cli: (cli ?? "").trim() };
  } catch {
    return null;
  }
}

/**
 * ensureLauncher writes cli.txt and the shim. It is pure file work: no shell,
 * no scheduler, cheap enough to run on every plugin load, which is what heals
 * the launcher after an update moved the plugin.
 *
 * A recorded interpreter that still exists is left alone even if this process
 * would pick a different one, so `install-schedule` chooses (with `force`) and
 * a plugin load only repairs: two writers disagreeing would rewrite the file
 * on every load.
 */
export function ensureLauncher({ interp = interpreter(), cli = cliPath(), force = false } = {}) {
  const dir = ensureDir(stateDir());
  const cliFile = path.join(dir, CLI_FILE);
  const wrote = [];

  const recorded = readLauncher(cliFile);
  const stale = !recorded || !exists(recorded.cli) || !exists(recorded.interp);
  if (force || stale) {
    if (writeIfChanged(cliFile, `${interp}\n${cli}\n`)) wrote.push(cliFile);
  }

  if (process.platform === "win32") {
    const shim = path.join(dir, WINDOWS_SHIM);
    if (writeIfChanged(shim, windowsShim())) wrote.push(shim);
    return { dir, cliFile, shim, wrote };
  }

  const shim = path.join(dir, POSIX_SHIM);
  if (writeIfChanged(shim, posixShim())) wrote.push(shim);
  try {
    fs.chmodSync(shim, 0o755);
  } catch {
    // a shim that cannot be made executable is still readable by /bin/sh
  }
  return { dir, cliFile, shim, wrote };
}

// ---- PowerShell without quoting games ---------------------------------------

function powershellFile(script) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "deepseek-peak-guard-"));
  const file = path.join(dir, "run.ps1");
  fs.writeFileSync(file, `\ufeff${script}\r\n`);
  try {
    return execFileSync(
      "powershell.exe",
      ["-NoProfile", "-NonInteractive", "-WindowStyle", "Hidden", "-ExecutionPolicy", "Bypass", "-File", file],
      { encoding: "utf8", windowsHide: true, stdio: ["ignore", "pipe", "pipe"], timeout: 60_000 },
    );
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

function psQuote(text) {
  return `'${String(text).replace(/'/g, "''")}'`;
}

function normaliseDays(days) {
  return String(days ?? "")
    .split(",")
    .map((day) => day.trim())
    .filter(Boolean)
    .join(",");
}

// Task Scheduler stores a weekly trigger's days as a bitmask, not as names.
const DAY_NAME = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"];
const DAY_BIT = [2, 4, 8, 16, 32, 64, 1]; // Mon=2 … Sat=64, Sun=1

function decodeDays(value) {
  const text = String(value ?? "").trim();
  const mask = Number(text);
  if (!text || !Number.isFinite(mask)) return normaliseDays(text);
  return DAY_NAME.filter((_, index) => (mask & DAY_BIT[index]) !== 0).join(",");
}

// ---- Windows ----------------------------------------------------------------

function windowsStatus() {
  const script = [
    `$name = ${psQuote(TASK)}`,
    "$task = Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue",
    "if (-not $task) { 'present=no'; exit 0 }",
    "'present=yes'",
    "'state=' + $task.State",
    "foreach ($trigger in $task.Triggers) {",
    "  $at = ([datetime]$trigger.StartBoundary).ToString('HH:mm')",
    "  $days = ($trigger.DaysOfWeek | ForEach-Object { $_.ToString() }) -join ','",
    "  'trigger=' + $at + '|' + $days",
    "}",
  ].join("\r\n");

  const info = { scheduler: "schtasks", task: TASK, present: false, state: null, triggers: [] };
  try {
    const out = powershellFile(script);
    for (const raw of out.split(/\r?\n/)) {
      const line = raw.trim();
      if (line === "present=yes") info.present = true;
      else if (line === "present=no") info.present = false;
      else if (line.startsWith("state=")) info.state = line.slice("state=".length);
      else if (line.startsWith("trigger=")) {
        const [at, days] = line.slice("trigger=".length).split("|");
        info.triggers.push({ at: String(at ?? "").trim(), days: decodeDays(days) });
      }
    }
  } catch (error) {
    info.error = sane(error?.stderr ?? error?.message ?? error);
  }
  return info;
}

function installWindows(config, launcher) {
  const plan = taskPlan(config);
  const triggers = plan.map((trigger, index) => ({
    name: `$t${index}`,
    line: `$t${index} = New-ScheduledTaskTrigger -Weekly -DaysOfWeek ${trigger.days} -At '${trigger.at}'`,
  }));

  const script = [
    "$ErrorActionPreference = 'Stop'",
    `$vbs = ${psQuote(launcher.shim)}`,
    `$action = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ('"' + $vbs + '" tick')`,
    ...triggers.map((trigger) => trigger.line),
    "$settings = New-ScheduledTaskSettingsSet -Hidden -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 30)",
    `Register-ScheduledTask -TaskName ${psQuote(TASK)} -Action $action -Trigger @(${triggers
      .map((trigger) => trigger.name)
      .join(",")}) -Settings $settings -Description 'DeepSeek peak guard: switch the DeepSeek Official provider at the price boundaries' -Force | Out-Null`,
    `'registered=' + (Get-ScheduledTask -TaskName ${psQuote(TASK)}).State`,
  ].join("\r\n");

  try {
    const out = powershellFile(script);
    const registered = /registered=(.*)/.exec(out)?.[1]?.trim() ?? null;
    return { scheduler: "schtasks", task: TASK, registered, triggers: plan, shim: launcher.shim };
  } catch (error) {
    return {
      scheduler: "schtasks",
      task: TASK,
      error: sane(error?.stderr ?? error?.message ?? error),
      shim: launcher.shim,
    };
  }
}

// ---- Linux ------------------------------------------------------------------

function unitDir() {
  const base = process.env.XDG_CONFIG_HOME?.trim() || path.join(os.homedir(), ".config");
  return path.join(base, "systemd", "user");
}

function unitPath(suffix) {
  return path.join(unitDir(), `${UNIT}.${suffix}`);
}

export function serviceContent(shim) {
  const places = [
    path.dirname(interpreter()),
    path.join(os.homedir(), ".local", "bin"),
    "/usr/local/bin",
    "/usr/bin",
    "/bin",
  ];
  return [
    "[Unit]",
    "Description=DeepSeek peak guard for magpie: one tick of the price clock",
    "",
    "[Service]",
    "Type=oneshot",
    `Environment="PATH=${[...new Set(places)].join(":")}"`,
    `ExecStart=/bin/sh "${shim}" tick`,
    "",
  ].join("\n");
}

export function timerContent(config) {
  return [
    "[Unit]",
    "Description=DeepSeek peak guard for magpie: the DeepSeek price boundaries",
    "",
    "[Timer]",
    ...systemdCalendar(config),
    "AccuracySec=1s",
    "Persistent=true",
    "",
    "[Install]",
    "WantedBy=timers.target",
    "",
  ].join("\n");
}

function systemctl(args) {
  return execFileSync("systemctl", ["--user", ...args], {
    encoding: "utf8",
    windowsHide: true,
    stdio: ["ignore", "pipe", "pipe"],
    timeout: 30_000,
  });
}

function nextFromListTimers() {
  try {
    const out = systemctl(["list-timers", `${UNIT}.timer`, "--no-pager"]);
    const row = out.split("\n").find((line) => line.includes(`${UNIT}.timer`));
    // "Tue 2026-11-03 09:00:00 CST   1h 26min left   Mon 2026-11-02 …"
    const next = row ? /^(\S+ \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} \S+)/.exec(row.trim()) : null;
    return next ? next[1] : null;
  } catch {
    return null;
  }
}

function installLinux(config, launcher) {
  const timer = unitPath("timer");
  const service = unitPath("service");
  writeIfChanged(service, serviceContent(launcher.shim));
  writeIfChanged(timer, timerContent(config));
  try {
    systemctl(["daemon-reload"]);
    systemctl(["enable", `${UNIT}.timer`]);
    // a timer that is already active keeps the calendar it started with, so a
    // re-install has to restart it for a changed schedule to take effect
    systemctl(["restart", `${UNIT}.timer`]);
    return { scheduler: "systemd", timer, service, shim: launcher.shim, next: nextFromListTimers() };
  } catch (error) {
    return {
      scheduler: "systemd",
      timer,
      service,
      shim: launcher.shim,
      error: sane(error?.stderr ?? error?.message ?? error),
    };
  }
}

// ---- what the plugin and the CLI use ---------------------------------------

/** install writes the schedule for this host; safe to run again any time. */
export function install({ config = loadConfig() } = {}) {
  const launcher = ensureLauncher({ force: true });
  const result = process.platform === "win32" ? installWindows(config, launcher) : installLinux(config, launcher);
  return {
    ...result,
    summary: describeSchedule(config),
    launcher: { cliFile: launcher.cliFile, shim: launcher.shim, wrote: launcher.wrote },
  };
}

/** uninstall takes the guard off the OS scheduler. */
export function uninstall() {
  if (process.platform === "win32") {
    const script = [
      `$name = ${psQuote(TASK)}`,
      "if (Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue) {",
      "  Unregister-ScheduledTask -TaskName $name -Confirm:$false",
      "  'removed=yes'",
      "} else { 'removed=no' }",
    ].join("\r\n");
    try {
      const out = powershellFile(script);
      return { scheduler: "schtasks", task: TASK, removed: /removed=yes/.test(out) };
    } catch (error) {
      return { scheduler: "schtasks", task: TASK, removed: false, error: sane(error?.stderr ?? error?.message ?? error) };
    }
  }
  try {
    systemctl(["disable", "--now", `${UNIT}.timer`]);
  } catch {
    // already gone
  }
  for (const suffix of ["timer", "service"]) fs.rmSync(unitPath(suffix), { force: true });
  try {
    systemctl(["daemon-reload"]);
  } catch {
    // nothing to reload
  }
  return { scheduler: "systemd", timer: unitPath("timer"), removed: true };
}

/**
 * status says whether the host still holds the schedule this config describes.
 * `match` is what `install-schedule` is for: false means the files on disk and
 * the config have drifted apart.
 */
export function status({ config = loadConfig() } = {}) {
  const launcher = { cliFile: path.join(stateDir(), CLI_FILE), shim: path.join(stateDir(), process.platform === "win32" ? WINDOWS_SHIM : POSIX_SHIM) };

  if (process.platform === "win32") {
    const info = windowsStatus();
    const expected = taskPlan(config);
    const match =
      info.present &&
      info.triggers.length === expected.length &&
      expected.every((want) => info.triggers.some((got) => got.at === want.at && got.days === want.days));
    return { ...info, expected, match, summary: describeSchedule(config), launcher };
  }

  const timer = unitPath("timer");
  const service = unitPath("service");
  const timerText = readText(timer);
  const serviceText = readText(service);
  return {
    scheduler: "systemd",
    timer,
    service,
    present: timerText !== null,
    match: timerText === timerContent(config) && serviceText === serviceContent(launcher.shim),
    expected: systemdCalendar(config),
    next: nextFromListTimers(),
    summary: describeSchedule(config),
    launcher,
  };
}

function readText(file) {
  try {
    return fs.readFileSync(file, "utf8");
  } catch {
    return null;
  }
}
